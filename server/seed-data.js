/** next occurrence of weekday `dow` (0=Sun) in Boston time, `weeks` weeks out, at hour:min */
function on(dow, hour, min = 0, weeks = 0) {
  const today = localDate(TZ)
  const todayDow = new Date(today + 'T12:00:00Z').getUTCDay()
  let diff = (dow - todayDow + 7) % 7
  if (diff === 0) diff = 7
  const date = localDate(TZ, diff + weeks * 7)
  return zonedToUtc(date, `${String(hour).padStart(2, '0')}:${String(min).padStart(2, '0')}`, TZ)
}

